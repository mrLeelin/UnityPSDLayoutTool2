namespace LicenseResultCodeNamespace
{
    internal enum LicenseResultCode : byte
    {
        // 此枚举在原程序集内没有具名字段。为保持 FieldDef 数量和后续元数据 Token 不变，
        // 这里只记录现有 byte 值的语义，不新增枚举成员：
        // 0  未产生结果             8  签名或完整性验证失败
        // 1  验证成功               9  产品不匹配
        // 2  配置或初始化失败       10 授权已暂停
        // 3  订单号无效             11 授权已撤销
        // 4  本地授权缓存不可用     12 支持期已过期
        // 5  网络错误               13 未授权当前功能
        // 6  产品元数据无效         14 当前设备受限
        // 7  远程授权不存在         15 离线授权保留码（当前仅用于遥测标签）
    }
}
